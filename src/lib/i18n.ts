const DICTS: Record<Locale, Dict> = {
  "zh-CN": zhCN,
  "zh-TW": zhTW,
  en,
};

export function translate(locale: string, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[(locale as Locale) in DICTS ? (locale as Locale) : "zh-CN"];
  let text = dict[key] ?? zhCN[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function useI18n() {
  const locale = useAppStore((s) => s.settings?.locale ?? "zh-CN");
  return {
    locale,
    t: (key: string, vars?: Record<string, string | number>) =>
      translate(locale, key, vars),
  };
}
